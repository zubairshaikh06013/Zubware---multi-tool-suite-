/** Prefer authored titles; the fallback preserves the complete tool name. */
export function getToolSeoTitle(tool: ToolMeta): string {
  if (tool.seoTitle) {
    return tool.seoTitle;
  }

  const mapped = TOOL_SEO_TITLES[tool.id];
  if (mapped) {
    return mapped;
  }

  // Graceful, robust fallback for future dynamic tools:
  let cleanBase = tool.title.replace(/\s*\|\s*Zubware/gi, '').trim();
  if (cleanBase.includes('—')) {
    return `${cleanBase} | Zubware`;
  }
  return `${cleanBase} - Free Online Tool | Zubware`;
}
