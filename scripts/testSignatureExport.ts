import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as signatureAppearance from '../src/lib/signatureAppearance';

// Exercise the real component effect with delayed canvas callbacks, including cleanup.
const source = fs.readFileSync('src/components/tools/image/SignatureResizerTool.tsx', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React } }).outputText;
const effects: Array<() => any> = [];
const blobs: Array<(b: any) => void> = [];
const writes: Array<[number, any]> = [];
const revoked: string[] = [];
let index = 0;
let exportThrows = false;
const values: Record<number, any> = { 1: {width: 20, height: 20}, 6: 140, 7: 60, 9: false };
const react = { createElement: (type: any, props: any, ...children: any[]) => ({type, props: {...props, children}}), useRef: () => ({current: 0}), useState: (initial: any) => { const i = index++; return [i in values ? values[i] : initial, (v: any) => writes.push([i, v])]; }, useEffect: (f: () => any) => effects.push(f) };
const ctx = { drawImage() {}, fillRect() {} };
const exports: any = {};
vm.runInNewContext(compiled, {exports, require: (name: string) => name === 'react' ? {...react, default: react} : name.includes('LanguageContext') ? {useLanguage: () => ({t: (s: string) => s})} : name.includes('signatureAppearance') ? signatureAppearance : name.includes('pdfUtils') ? {formatBytes: String} : {}, document: {createElement: () => ({getContext: () => ctx, toBlob: (cb: any) => { if (exportThrows) throw new Error('Encoding failed'); blobs.push(cb); }})}, URL: {createObjectURL: () => 'blob:preview', revokeObjectURL: (s: string) => revoked.push(s)} });
const view = exports.SignatureResizerTool({onShowToast() {}});
const nodes = (node: any): any[] => Array.isArray(node) ? node.flatMap(nodes) : node && typeof node === 'object' ? [node, ...nodes(node.props?.children)] : [];
const customLimit = nodes(view).find(node => node.type === 'input' && node.props.placeholder === 'कोई सीमा नहीं');
assert(customLimit, 'Custom maximum KB input must be available');
for (const [input, expected] of [['30', 30], ['', null], ['-1', null], ['10001', 10000], ['abc', null]] as const) {
  customLimit.props.onChange({target: {value: input}});
  assert(writes.some(([i,v]) => i === 12 && v === expected), `Custom limit ${input} must produce ${expected}`);
  writes.length = 0;
}
const render = effects[1];
const cleanup = render();
cleanup();
blobs.shift()!({size: 200});
assert(!writes.some(([i,v]) => i === 13 && v), 'Cancelled export must not publish a stale blob');
const cleanup2 = render();
blobs.shift()!({size: 200});
assert(writes.some(([i,v]) => i === 14 && v === 'blob:preview'), 'Current export must publish its preview');
cleanup2();
assert.deepEqual(revoked, ['blob:preview'], 'Preview URL must be released');
writes.length = 0;
const cleanup3 = render();
blobs.shift()!(null);
assert(writes.some(([i,v]) => i === 18 && v), 'Null export must show an error instead of an endless preview');
assert(!writes.some(([i,v]) => i === 13 && v), 'Failed export must not enable download');
cleanup3();
writes.length = 0;
exportThrows = true;
const cleanup4 = render();
assert(writes.some(([i,v]) => i === 18 && v), 'Thrown encoding error must be reported');
cleanup4();
console.log('Signature export: stale callbacks ignored; preview published; URLs released; null and thrown encoding failures reported.');
