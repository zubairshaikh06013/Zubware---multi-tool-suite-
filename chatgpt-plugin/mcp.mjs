import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { registerAppResource, registerAppTool, RESOURCE_MIME_TYPE } from '@modelcontextprotocol/ext-apps/server';
import { z } from 'zod';
import catalog from './generated/catalog.json' with { type: 'json' };
export const RESOURCE_URI = 'ui://zubware/tools-v1.html';
export const categories = [...new Set(catalog.map(t => t.category))];
export function searchCatalog({ query = '', category = '', offset = 0, limit = 20 } = {}) {
  const terms = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  const matches = catalog.filter(t => (!category || t.category === category) && terms.every(term =>
    [t.id,t.title,t.description,t.category,...t.features].join(' ').toLowerCase().includes(term)));
  return { total:matches.length, offset, limit, tools:matches.slice(offset,offset + limit) };
}
const instructions = 'Zubware provides interactive browser tools. Use search_tools to discover tools and open_tool to display one. Users choose inputs and process files in the panel. These MCP calls never process, upload, or download user files. Never claim a file was processed or a result generated by opening a tool. All embedded tools await ChatGPT compatibility testing. If the panel fails, offer the canonical website URL. Do not request passwords, identity documents, financial records or confidential notes in chat; users can enter private inputs directly in the tool where appropriate.';
export function createZubwareServer({ html, assetOrigin }) {
  const origin = new URL(assetOrigin).origin;
  const server = new McpServer({ name:'zubware', version:'0.1.0' }, { instructions });
  registerAppResource(server, 'zubware-tools', RESOURCE_URI, {}, async () => ({ contents:[{
    uri:RESOURCE_URI,mimeType:RESOURCE_MIME_TYPE,
    text:html.replace(/(src|href)="\/(?!\/)/g, `$1="${origin}/`),
    _meta:{ ui:{ prefersBorder:true,csp:{
      resourceDomains:[origin,'https://www.zubware.com','https://cdn.jsdelivr.net','https://unpkg.com','https://huggingface.co','https://*.huggingface.co','https://*.hf.co','blob:','data:'],
      connectDomains:[origin,'https://api.zubware.com','https://www.zubware.com','https://cdn.jsdelivr.net','https://unpkg.com','https://huggingface.co','https://*.huggingface.co','https://*.hf.co'],
    } } },
  }] }));
  const annotations = { readOnlyHint:true,destructiveHint:false,idempotentHint:true,openWorldHint:false };
  const reply = (text, structuredContent) => ({ content:[{type:'text',text}], structuredContent });
  server.registerTool('list_categories',{
    title:'List Zubware categories', description:'List every tool category and the number of tools in each category.', inputSchema:{}, annotations,
  },async () => reply('Zubware tool categories.',{ total:catalog.length,categories:categories.map(name => ({name,count:catalog.filter(t=>t.category===name).length})) }));
  registerAppTool(server,'search_tools',{
    title:'Search all Zubware tools',description:'Find tools across the entire Zubware website. Returns canonical URLs and paginated results. Search English names such as photo, PDF, resume, tax, video, or calculator. This discovers tools; it does not process inputs.',
    inputSchema:{query:z.string().max(300).default(''),category:z.string().max(150).default(''),offset:z.number().int().min(0).default(0),limit:z.number().int().min(1).max(50).default(20)},annotations,
    _meta:{ui:{resourceUri:RESOURCE_URI}},
  },async args => reply('Choose a tool to use its interactive panel.',{...searchCatalog(args),query:args.query,category:args.category}));
  registerAppTool(server,'open_tool',{
    title:'Open a Zubware tool',description:'Display the existing Zubware tool interface inside the panel by its exact ID from search_tools. Users supply inputs and run the tool themselves. This call does not execute the tool or process any files.',
    inputSchema:{toolId:z.string().min(1).max(150)},annotations,_meta:{ui:{resourceUri:RESOURCE_URI}},
  },async ({toolId}) => {
    const tool = catalog.find(t=>t.id===toolId);
    if (!tool) return {isError:true,content:[{type:'text',text:'Unknown tool ID. Use search_tools to find a valid ID.'}]};
    return reply(`Opened ${tool.title}. Choose inputs in the panel. No file has been processed.`,{toolId,tool,status:'awaiting_user_input'});
  });
  return server;
}
